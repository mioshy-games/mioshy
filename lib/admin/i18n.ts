const TABLES: Record<AdminLocale, Dict> = { en: EN, he: HE };

/**
 * Look up a key in the chosen locale. Falls back to English when the
 * key is missing in Hebrew. Falls back to the key itself if both miss
 * (so we never crash and the missing key surfaces visibly).
 */
export function t(locale: AdminLocale, key: string): string {
  return TABLES[locale][key] ?? EN[key] ?? key;
}

/**
 * Bind a translator to a specific locale. Convenient inside server
 * components that already know their locale.
 */
export function makeT(locale: AdminLocale): (key: string) => string {
  return (key: string) => t(locale, key);
}
